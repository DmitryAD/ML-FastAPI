"""
День 1. Базовое приложение FastAPI.

Здесь я поднимаю минимальный веб-сервис, на который дальше буду
навешивать всё остальное: загрузку датасета, обучение модели,
эндпоинт предсказания churn.

Пока сервис умеет только одно - отвечать на GET / и говорить, что он жив.
Этого достаточно, чтобы убедиться, что окружение настроено и связка
FastAPI + uvicorn работает.

Запуск (из папки с этим файлом):
    uvicorn main:app --reload
"""

"""
FastAPI - это класс, из которого создаётся само веб-приложение.
Как он работает: я создаю объект приложения, а потом через декораторы
(@app.get, @app.post и т.д.) "регистрирую" в нём обычные питоновские функции.
Когда приходит HTTP-запрос, FastAPI смотрит на метод и путь запроса,
находит подходящую функцию, вызывает её, а то, что функция вернула,
превращает в JSON и отправляет клиенту.
"""
from fastapi import FastAPI


"""
Создаю объект приложения. Именно на него ссылается команда запуска
uvicorn main:app - "в файле main.py возьми переменную app".

title - необязательный параметр, это просто название сервиса,
которое будет показано в автодокументации на /docs.
"""
app = FastAPI(title="ML Churn Service")


"""
Декоратор @app.get("/") говорит приложению: если пришёл запрос
методом GET на адрес "/" (корень сервиса), вызови функцию ниже.

GET - метод "дай мне данные", он ничего не меняет на сервере,
поэтому для простой проверки "сервис жив?" подходит именно он.

Функция возвращает обычный словарь. Превращать его в JSON руками
не нужно - FastAPI сделает это сам.
"""
@app.get("/")
def root():
    return {"message": "ml churn service is running"}
